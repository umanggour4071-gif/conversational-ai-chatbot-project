// Copies third-party browser assets from node_modules into static/ so the app can serve them
// itself (no CDN at runtime). Run with:  npm install && npm run vendor
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const nm = (p) => join(root, "node_modules", p);
const out = (p) => join(root, "static", p);
const version = (pkg) => JSON.parse(readFileSync(nm(`${pkg}/package.json`), "utf8")).version;

mkdirSync(out("vendor"), { recursive: true });
mkdirSync(out("fonts"), { recursive: true });

copyFileSync(nm("marked/lib/marked.umd.js"), out("vendor/marked.umd.js"));
copyFileSync(nm("dompurify/dist/purify.min.js"), out("vendor/purify.min.js"));
copyFileSync(nm("@fontsource-variable/bricolage-grotesque/files/bricolage-grotesque-latin-wght-normal.woff2"), out("fonts/bricolage-grotesque-latin.woff2"));
copyFileSync(nm("@fontsource-variable/instrument-sans/files/instrument-sans-latin-wght-normal.woff2"), out("fonts/instrument-sans-latin.woff2"));
copyFileSync(nm("@fontsource/jetbrains-mono/files/jetbrains-mono-latin-400-normal.woff2"), out("fonts/jetbrains-mono-latin-400.woff2"));

writeFileSync(out("vendor/README.md"), `# Vendored third-party assets

Generated by \`npm run vendor\` (scripts/sync_vendor.mjs). Do not edit by hand.

| File | Package | Version | License |
|---|---|---|---|
| vendor/marked.umd.js | marked | ${version("marked")} | MIT |
| vendor/purify.min.js | dompurify | ${version("dompurify")} | Apache-2.0 OR MPL-2.0 |
| fonts/bricolage-grotesque-latin.woff2 | @fontsource-variable/bricolage-grotesque | ${version("@fontsource-variable/bricolage-grotesque")} | SIL OFL 1.1 |
| fonts/instrument-sans-latin.woff2 | @fontsource-variable/instrument-sans | ${version("@fontsource-variable/instrument-sans")} | SIL OFL 1.1 |
| fonts/jetbrains-mono-latin-400.woff2 | @fontsource/jetbrains-mono | ${version("@fontsource/jetbrains-mono")} | SIL OFL 1.1 |
`);
console.log("Vendored assets updated.");
